%% Mini detection 
% Run this script in sections (aka 'cells') using the 'Run section' button,
% rather than running it all at once. Numbered items should be read and
% relevent settings set by user
%
%    
% 1) Specify the experiment folder (where all data from single
% experiment is saved) and trial folder (specific folder where trial to be
% analyzed is saved). If these are the same, just set trial_folder =
% exp_folder. If more than one trial is in this folder, also specify the file
% name of the specific recording to be analyzed, otherwise if this is left 
% blank, the first recording is grabbed automatically 

% Path to data and ROIs
exp_folder = fullfile(fileparts(which('test_mini_detection.m')),'test_data',...
                    '20220802_GluSnFR3_SynmRuby_dish3_350mM_sucrose');
trial_folder = exp_folder;
rec_name = '350mM_sucrose'; % name of recording file, if left empty, grabs first file in trial_folder

% 2) Specify ROI set zip file (output of saving ROIs in ImageJ)

roiset_name = 'RoiSet_auto_wash.mat';

% 3) If desired, specify the specific ROIs to be analyzed, either using a
% cell array of strings, ex:
%   roi_names = {'ROI001','ROI002'};
% OR, as shown below, use the numericVec2chars helper function to specify
% an array of integers and the string pattern to avoid having to retype
% 'ROI'. 
%  If analyzing all ROIs in the ROIset file, leave this blank, either of 
%  these options work:
%    roi_names = ''; 
%    roi_names = []; 

% roi_names = numericVec2chars([1,2,3,18,47,49,53],'ROI%03d'); % ROI indices to extract
roi_names = []; 

% 4) Specify whether to plot image of recording, save figures, and use
% motion correction (usually not necessary and can be slow, I recommend
% skipping)
% Analysis script settings
save_mini_output = 1; % Set to 1 to save mini output to spreadsheets and .mat file
plot_img = 1; % Set to 1 to plot mean F image with  ROIs first, 0 to skip
save_figs = 1; % Set to 1 to save images generated by this script, 0 to skip
mot_correct = 0; % motion correction - SLOW, usually not necessary

% 5) Specify your sampling rate and frames at which stimuli were applied.
% If no stimuli were applied, leave stim_times, stim_wind, and baseline_wind blank
% Experiment/imaging settings
sampling_rate = 200; % Hz
stim_times = defineStimTrain(0,0.5,41); 
stim_wind = 0.2; % sec to analyze after each stim (also gets blanked in detectMinis)
baseline_wind = 0.05; % sec for baseline window 
units = 'sec'; % 'sec' or 'frames'
exp_settings = ExperimentSettings(stim_times,stim_wind,baseline_wind,units,sampling_rate); 

%% Load recording

if isempty(rec_name)
    rec_names = getImagesWithinDir(trial_folder); 
    rec_name = rec_names{1}; 
end
% Note: If rerunning parts of this script, you should only need to run this
% section once to load the recording and skip it if running other sections
rec = Recording(fullfile(trial_folder,rec_name),'pixel_size',pixelSize('loki'));  
rec.load(); 
% Apply motion correction if necessary 
if mot_correct
    rec = motionCorrectRecording(rec,1:10); % motion correct using mean of first 10 frames as reference
end

rois = ROIs(fullfile(exp_folder,roiset_name)); 
[~,roi_inds] = intersect(rois.names,roi_names);
if ~isempty(roi_inds)
    rois = rois.slice(roi_inds);
    rois.save('rois_test.mat')
end
if plot_img
    peak_img = max(rec.vals,[],3);
    mean_img = mean(rec.vals,3);
    fig = figure('Units','normalized','Position',[0 0.14 0.9 0.75]); 
    imagesc(mean_img); axis off; axis equal; axis tight; 
    hold on;
    colormap(inferno(1000));
    rois.plot('y',gca,1,1);
    colorbar
    caxis(quantile(mean_img(:),[0.05 0.999]));
    set(gca,'YDir','reverse') % 'reverse' (default) matches ImageJ
    if save_figs
         printFig(fig,fullfile(rec.filedir,'mini_analysis'),[rec.img_name,'_mean'],...
            'formats','png','resolutions','-r300')
    end
end
%% Extract traces in ROIs
% Note: may take some time, also should only need to run once if re-running
% other parts of the script, e.g. mini detection below
func_output = calcROIfuncs(rec,rois,{'mean','baseline'},exp_settings,...
                            'separate');
means = func_output.mean; % [num_timepoints x num_rois] matrix of mean values 
                          % within each roi at each frame 
t = func_output.trec; % time vector
%% Run mini detection
% 6) Description of settings are below. Most can be left to defaults, main
% settings you may want to adjust are threshold, snr_thresh, nframes_back,
% nframes_forward, min_mini_width, deconv_tau (all described below)
% for visualization and saving, set the plot_filt_output_roi_index and
% plot_figs variables
% Mini detector settings
settings = struct();
% Peak detection
settings.threshold = 10; % threshold for peak detection on filtered trace. 
                        % Defined as multiple above noise level (std of
                        % baseline fluctations)
settings.snr_thresh = 5; % 4.5 throw out minis with 
                         % mini SNR (peak/std(baseline)) less than this number 
                         % (based on raw F trace). Set to 0 to skip this. 
settings.nframes_back = round(0.15*sampling_rate); % number of frames before each mini peak to extract
settings.nframes_forward = round(0.25*sampling_rate); % number of frames after each mini peak to extract
settings.min_mini_width = 1/sampling_rate; % sec - minimum peak width, 
                                            % using findpeaks.m definition of width (default 'halfprom')
settings.min_peak_distance = 0.1; % sec - min distance between mini peaks to allow
% Filtering
settings.deconv = 1; % set to 1 to use deconvolution, may need to adjust threshold if turned off
settings.apply_filter = 1;
settings.filt_type = 'gauss'; % filter type, 'gauss' for gaussian or 'butter' for butterworth
settings.refilter_deconv = 1; % 1 to refilter deconvolved trace (usually doesn't have much effect, can skip)
settings.smooth_filt_width = 5; % width of median smoothing filter, takes 
                                % moving median of this number of frames,
                                % usually not needed, especially if using
                                % lower sampling rate, b/c it can cause
                                % smooth out peaks too much
settings.fc = [0.5 60]; % Hz - highpass filter cutoff frequences, gets rid 
                     % of baseline fluctuations
settings.deconv_tau = 45e-3; % ms decay time constant for deconvolution. 
                              % Uses single exponential decay with this
                              % time constant to enhance SNR of events with
                              % similar shape, time constant should match
                              % decay time constant of minis in your
                              % recordings, which can be measured after
                              % detection below
% Clean up
settings.stim_frames = exp_settings.stim_vals; % ignore if no stim
settings.blank_around_stim = [exp_settings.baseline_wind,round(exp_settings.stim_wind/2)]; % ignore if no stim
settings.find_pk_frame = round(0.025*exp_settings.sampling_rate);% look 25 ms around peak from filtered F in raw F to get actual peak time                              
settings.num_frames_skip_start_end = round(0.8*exp_settings.sampling_rate); % frames to remove from start/end due to filtering artifacts
settings.use_asls_baseline = 1;  % 1  to use asymmetric least squares baseline removal
                                 % 0 uses simple average of nframes_back
                                 % frames before each peak, may be less
                                 % robust for minis immediately after other
                                 % minis
settings.asls_smoothness = 100; % smoothness param for asymmetric least squares (see asLS_baseline.m for description)
settings.asls_asym = 0.4; % asymmetry parameter for asymmetric least squares
% plotting and file saving
settings.plot_filt_output_roi_index = 1; % plot example of filtering in this roi
settings.plot_figs = 1; % 1 to plot mini detection figures, 0 to skip
settings.save_figs = save_figs; % 1 to save figures, 0 to skip
settings.save_figs_dir = fullfile(rec.filedir,'mini_analysis'); % save figures to this directory (saves to current directory if empty)
settings.trial_name = rec.img_name; % for file saving
% Run 
mini_output = detectMinis(means,exp_settings.sampling_rate,settings); 
% Output mini data to .mat file and spreadsheet
if save_mini_output    
    saveMiniOutput(mini_output,rec,rois,exp_settings);
end
%% Plot traces in all with minis overlaid
% set offset factor for traces automatically, but if this doesn't work, may
%  need to set manually
offset_factor = max(max(func_output.mean,[],1)-mean(func_output.mean,1))*1.1; 
fig = figure('Units','inches','Position',[0.4479    1.3021   19.0625    8.9583]); 
ax = gca;
plotROIfunc(func_output,'mean',exp_settings.stim_vals,...
            [],'ax',ax,...
            'show_legend',0,'rois',rois,'offset_factor',offset_factor,...
            'sbar_len',offset_factor/2,'title_on',0);
offset = linspace(rois.num_rois*offset_factor,...
                                    0,rois.num_rois);
cols = lines(rois.num_rois);
for i = 1:rois.num_rois
    Fi = func_output.mean(:,i);
    non_nan_frames = find(~isnan(Fi));
    Fi = Fi - Fi(non_nan_frames(1),:) + offset(i); % start all traces at 0 for plot    
    if ~isempty(mini_output.mini_frames{i})
%         mini_heightsi = max(mini_output.mini_F_traces_roi{i},[],1)' - mean(mini_output.mini_F_traces_roi{i}(1:settings.nframes_back,1))';
        
        plot(mini_output.mini_frames{i},Fi(mini_output.mini_frames{i}),'o','MarkerEdgeColor',cols(i,:),...
                'MarkerFaceColor','k');
    end
end
if save_figs
    printFig(fig,fullfile(rec.filedir,'mini_analysis'),[rec.img_name,'_meanF_with_minis'])
end
%% Calculate time constants of minis within ROI and for mean mini across ROIs 
t_aligned = exp_settings.getTimeVector(size(mini_output.mini_F_traces,1));
t_aligned = t_aligned - t_aligned(settings.nframes_back + 1);
mini_deltaF_F_traces = mini_output.mini_deltaF_F_traces;
mini_mean_deltaF_F = mean(mini_deltaF_F_traces,2,'omitnan');
mini_mean_deltaF_F_rois = cell2mat(cellfun(@(x) mean(x,2,'omitnan'),mini_output.mini_deltaF_F_traces_roi,'UniformOutput',0));
% Fit decay to single exp on mean trace
[peakF,ind] = max(mini_mean_deltaF_F);
F_fit = mini_mean_deltaF_F(ind:end);
t_fit = t_aligned(ind:end); t_fit = t_fit-t_fit(1); 
decay_fit = fitExpDecay(t_fit,F_fit,1);
% fit individual roi mean traces
t_fit2 = t_aligned(settings.nframes_back + 1:end); % account for 1 frame shift due to peak detection on filtered trace
F_fit2 = mini_mean_deltaF_F_rois(settings.nframes_back + 1:end,:); 
decay_fits_all = fitExpDecay(t_fit2,F_fit2,1,'align_traces',0); 
%% Plot time constant analysis
fig = figure('Units','inches'); 
fig.Position(3:4) = [16 6]; 
subplot(1,2,1)
plot(t_aligned*1e3,mini_mean_deltaF_F,'k');
hold on; 
plot(1e3*(decay_fit.t_fits{1} + t_aligned(ind)),decay_fit.fitobjs{1}(decay_fit.t_fits{1}),'--r')
box off; 
xlabel('time (ms)'); ylabel('\Delta F/F_{0}');
title('Mean mini and fit to single exponential decay','FontSize',14);
legend('Mean',sprintf('\\tau_{d} = %.2f ms',decay_fit.taud1*1e3),'Box','off')
subplot(1,2,2)
plot(decay_fits_all.taud1*1e3,'-o'); box off; 
xlabel('ROI index');
ylabel('\tau_{d} (ms)')
title('Decay fits on mean mini within ROI','FontSize',14)